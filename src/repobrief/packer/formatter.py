"""Output format generators for the packed digest.

Supports three formats: Markdown, XML, and Plain Text.
Each takes the same inputs and produces a single string ready
for saving to disk or passing to an LLM.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import Enum
from pathlib import Path
from xml.sax.saxutils import escape as xml_escape

from repobrief import __version__
from repobrief.packer.tree import render_directory_tree
from repobrief.scanner.models import ScannedFile
from repobrief.scoring.tokenizer import count_tokens


class OutputFormat(Enum):
    """Supported output formats."""

    MARKDOWN = "markdown"
    XML = "xml"
    PLAIN = "plain"


@dataclass
class PackingMetadata:
    """Metadata about the packing operation, used in the digest header.

    Attributes:
        repo_name: Name of the repository (directory name).
        files_included: Number of files in the digest.
        files_scanned: Total files found by the scanner (before filtering).
        tokens_used: Total tokens in the selected files.
        token_budget: The configured token budget.
    """

    repo_name: str
    files_included: int
    files_scanned: int
    tokens_used: int
    token_budget: int


